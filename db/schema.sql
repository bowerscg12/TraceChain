-- TraceChain off-chain item details (spike schema v1). Values are stored ALREADY NORMALIZED (see SERIALIZATION_SPEC.md §2).
CREATE SEQUENCE IF NOT EXISTS item_seq START 1;

CREATE TABLE IF NOT EXISTS item_details (
  item_id                text        PRIMARY KEY,                         -- TC-YYYY-NNNNNN, generated by the API from item_seq
  brand                  text        NOT NULL,
  style_code             text        NOT NULL,
  colorway               text        NOT NULL,
  size                   text        NOT NULL,                            -- string on purpose ("10.5", "09")
  manufacturer           text        NOT NULL,
  country_of_manufacture text        NOT NULL,
  production_batch       text        NOT NULL,
  production_date        date        NOT NULL,                            -- read back as raw text via pg type parser for OID 1082
  registered_by          text        NOT NULL,                            -- lowercase 0x + 40 hex
  status                 text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed')),
  created_at             timestamptz NOT NULL DEFAULT now()
);
